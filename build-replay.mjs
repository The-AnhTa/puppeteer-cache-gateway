/*
 * ---------------------------------------------------------------
 * HTML escaping.
 *
 * Snapshot text is DATA, not trusted HTML.
 * ---------------------------------------------------------------
 */

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');
}

/*
 * ---------------------------------------------------------------
 * Common CSP.
 *
 * There are deliberately:
 *
 * - no external scripts
 * - no images
 * - no network connections
 * - no forms
 * - no frames
 *
 * JavaScript is inline and generated by us solely for local search.
 * ---------------------------------------------------------------
 */

const CSP = [
  "default-src 'none'",
  "style-src 'unsafe-inline'",
  "script-src 'unsafe-inline'",
  "img-src 'none'",
  "connect-src 'none'",
  "font-src 'none'",
  "media-src 'none'",
  "object-src 'none'",
  "frame-src 'none'",
  "form-action 'none'",
  "base-uri 'none'"
].join('; ');

/*
 * ---------------------------------------------------------------
 * Navigation bar.
 * ---------------------------------------------------------------
 */

function renderNavigation(
  currentSlug
) {
  return VIEWS
    .map((view) => {
      const current =
        view.slug === currentSlug;

      const className =
        current
          ? 'nav-link active'
          : 'nav-link';

      return `
        <a
          class="${className}"
          href="./${view.slug}.html"
        >${escapeHtml(view.label)}</a>
      `;
    })
    .join('\n');
}

