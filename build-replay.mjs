const latestPath =
  path.join(
    CACHE_DIR,
    'latest.json'
  );

const latest =
  JSON.parse(
    await fs.readFile(
      latestPath,
      'utf8'
    )
  );

const collection =
  latest.collection;

/*
 * Collection names must be a simple directory name.
 *
 * Prevent path traversal such as ../../something.
 */

if (
  typeof collection !== 'string' ||
  !/^[A-Za-z0-9._-]+$/.test(
    collection
  )
) {
  throw new Error(
    'Invalid collection name in latest.json'
  );
}

const collectionDir =
  path.resolve(
    COLLECTIONS_DIR,
    collection
  );

const collectionsRoot =
  path.resolve(
    COLLECTIONS_DIR
  ) + path.sep;

if (
  !collectionDir.startsWith(
    collectionsRoot
  )
) {
  throw new Error(
    'Collection path escaped collections directory'
  );
}

console.log(
  `Source collection: ${collection}`
);

console.log(
  `Source directory:  ${collectionDir}`
);

console.log('');

/*
 * ---------------------------------------------------------------
 * Load only the fixed allowlisted files.
 * ---------------------------------------------------------------
 */

const loadedViews =
  [];

const viewMetadata =
  new Map();

for (const view of VIEWS) {

  const textPath =
    path.join(
      collectionDir,
      `${view.slug}.txt`
    );

  const metadataPath =
    path.join(
      collectionDir,
      `${view.slug}.json`
    );

  const text =
    await fs.readFile(
      textPath,
      'utf8'
    );

  const metadata =
    JSON.parse(
      await fs.readFile(
        metadataPath,
        'utf8'
      )
    );

  /*
   * Make sure the metadata corresponds to
   * the expected hard-coded control.
   */

  if (
    metadata.control !==
    view.control
  ) {
    throw new Error(
      `${view.slug}: metadata control mismatch`
    );
  }

  /*
   * Important:
   *
   * We deliberately do NOT copy metadata.url
   * into the replay site.
   */

  loadedViews.push({
    view,
    text,
    metadata
  });

  viewMetadata.set(
    view.control,
    metadata
  );
}

/*
 * ---------------------------------------------------------------
 * Build into a temporary directory first.
 * ---------------------------------------------------------------
 */

await fs.mkdir(
  REPLAY_ROOT,
  {
    recursive: true
  }
);

const tempDir =
  path.join(
    REPLAY_ROOT,
    `.latest-tmp-${process.pid}`
  );

await fs.rm(
  tempDir,
  {
    recursive: true,
    force: true
  }
);

await fs.mkdir(
  tempDir,
  {
    recursive: true
  }
);

/*
 * Home page.
 */

await fs.writeFile(
  path.join(
    tempDir,
    'index.html'
  ),

  renderIndexPage(
    collection,
    viewMetadata
  ),

  'utf8'
);

/*
 * Seven replay pages.
 */

for (
  const item of loadedViews
) {

  const html =
    renderViewPage({
      collection,
      view:
        item.view,
      text:
        item.text,
      metadata:
        item.metadata
    });

  const outputPath =
    path.join(
      tempDir,
      `${item.view.slug}.html`
    );

  await fs.writeFile(
    outputPath,
    html,
    'utf8'
  );

  console.log(
    `Generated: ${item.view.slug}.html`
  );
}

/*
 * ---------------------------------------------------------------
 * Safe replay manifest.
 *
 * Notice that no SEMS+ URL is copied here.
 * ---------------------------------------------------------------
 */

const replayManifest = {
  generatedAt:
    new Date().toISOString(),

  collection,

  source:
    'sanitized-cache',

  networkRequired:
    false,

  views:
    VIEWS.map(
      view => ({
        control:
          view.control,

        label:
          view.label,

        file:
          `${view.slug}.html`
      })
    )
};

await fs.writeFile(
  path.join(
    tempDir,
    'replay-manifest.json'
  ),

  JSON.stringify(
    replayManifest,
    null,
    2
  ),

  'utf8'
);

/*
 * ---------------------------------------------------------------
 * Replace replay/latest only after the new replay has been built.
 * ---------------------------------------------------------------
 */

await fs.rm(
  REPLAY_DIR,
  {
    recursive: true,
    force: true
  }
);

await fs.rename(
  tempDir,
  REPLAY_DIR
);

console.log('');
console.log(
  'REPLAY BUILD SUCCESS'
);

console.log(
  `Directory: ${REPLAY_DIR}`
);

console.log(
  `Views: ${VIEWS.length}`
);